@router.message(F.voice)
async def handle_voice(message: Message, bot):

    # Голосовые анализируются только после нажатия «💬Хочу поговорить».
    if message.from_user.id not in talk_mode_users:
        await message.answer(
            "💬 Чтобы я мог разобрать голосовое сообщение, сначала нажмите кнопку «💬Хочу поговорить»."
        )
        return

    voice_path = None

    try:
        await message.answer(
            "🎙 Голосовое получено.\n\n"
            "⏳ Перевожу речь в текст и анализирую сообщение..."
        )

        voice_file = await bot.get_file(message.voice.file_id)

        with tempfile.NamedTemporaryFile(
            suffix=".ogg",
            delete=False
        ) as temporary_file:
            voice_path = temporary_file.name

        await bot.download_file(
            voice_file.file_path,
            destination=voice_path
        )

        if not os.path.exists(voice_path) or os.path.getsize(voice_path) == 0:
            raise Exception("Голосовой файл не был скачан или оказался пустым.")

        segments, info = whisper_model.transcribe(
            voice_path,
            language="ru",
            beam_size=5,
            vad_filter=True
        )

        text_parts = []
        for segment in segments:
            segment_text = segment.text.strip()
            if segment_text:
                text_parts.append(segment_text)

        request_text = " ".join(text_parts).strip()

        if not request_text:
            await message.answer(
                "❌ Не удалось разобрать речь.\n\n"
                "Попробуйте записать голосовое ещё раз и говорить немного громче."
            )
            return

        # Критическое голосовое сообщение НЕ анализируем.
        # Сразу отправляем кризисную инструкцию и контакты.
        if is_crisis_text(request_text):
            await message.answer(
                CRISIS_RESPONSE,
                parse_mode=ParseMode.HTML
            )
            await message.answer(
                get_specialist_contacts_text(),
                parse_mode=ParseMode.HTML,
                disable_web_page_preview=True
            )
            return

        result = analyze_text(request_text)

        for start in range(0, len(result), 4090):
            await message.answer(
                result[start:start + 4090],
                parse_mode=ParseMode.HTML
            )

    except Exception as error:
        print()
        print("=" * 60)
        print("ОШИБКА ПРИ ОБРАБОТКЕ ГОЛОСОВОГО")
        print("=" * 60)
        print(type(error).__name__)
        print(str(error))
        print("=" * 60)
        print()

        await message.answer(
            "❌ Не удалось обработать голосовое сообщение.\n\n"
            "Попробуйте записать его ещё раз."
        )

    finally:
        if voice_path and os.path.exists(voice_path):
            try:
                os.remove(voice_path)
            except Exception as error:
                print("Ошибка удаления временного файла:", error)



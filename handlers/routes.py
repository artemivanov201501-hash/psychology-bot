@router.message(Command("start"))
async def start_command(message: Message):

    talk_mode_users.discard(message.from_user.id)

    first_name = message.from_user.first_name or "друг"

    await message.answer(
        f"Здравствуй, {first_name}! "
        "Я бот, который может помочь тебе разобраться "
        "со своими переживаниями.\n\n"
        "Нажми «🏠Меню», чтобы узнать, как начать. 🤍",
        reply_markup=get_main_reply_keyboard()
    )

